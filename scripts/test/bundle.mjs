'use strict'

import {build} from 'esbuild'
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import {createRequire} from 'node:module'
import {fileURLToPath, pathToFileURL} from 'node:url'
import {bundleFile, projectRoot} from './paths.mjs'

const require = createRequire(import.meta.url)
const esbuildVersion = JSON.parse(fs.readFileSync(require.resolve('esbuild/package.json'), 'utf8')).version

// Bump when the bundle build options below change in a way that alters the
// output (entry shape, plugins, sourcemap handling, ...).
const BUNDLE_SIGNATURE_VERSION = 1

function collectSrcModules() {
  const files = []
  const srcDir = path.join(projectRoot, 'src')
  const entries = fs.readdirSync(srcDir, {recursive: true, withFileTypes: true})
  for (const entry of entries) {
    if (!entry.isFile()) continue
    if (!entry.name.endsWith('.ts') || entry.name.endsWith('.d.ts')) continue
    const rel = path.relative(projectRoot, path.join(entry.parentPath, entry.name))
    if (rel.includes('__tests__')) continue
    files.push(rel.replace(/\.ts$/, ''))
  }
  return files.sort()
}

/**
 * Third-party packages referenced by the src modules that make up the bundle.
 * These are bundled INTO the runtime and exported under `pkg:<spec>` keys so
 * tests reference the exact same instances instead of loading node_modules
 * again.
 */
function collectPackages() {
  const pkg = JSON.parse(fs.readFileSync(path.join(projectRoot, 'package.json'), 'utf8'))
  return Object.keys(pkg.dependencies || {}).sort()
}

/**
 * Packages whose `exports` map ships different builds for `import` vs
 * `require` (ESM vs UMD, e.g. vscode-uri). esbuild would inline the ESM copy
 * for src imports and the UMD copy for the entry's pkg: require, producing
 * two URI classes and breaking `instanceof`. Pin every import of these
 * packages (and subpaths) to the single require/default build.
 */
const DUAL_BUILD_PACKAGES = new Set([
  'vscode-uri',
  'vscode-languageserver-textdocument',
  'vscode-languageserver-types',
])

const pinDualBuildPackages = {
  name: 'pin-dual-build-packages',
  setup(build) {
    build.onResolve({filter: /./}, args => {
      if (args.kind === 'entry-point') return
      const spec = args.path
      if (spec.startsWith('.') || spec.startsWith('/') || spec.startsWith('\\') || spec.startsWith('node:')) return
      const top = spec.startsWith('@') ? spec.split('/').slice(0, 2).join('/') : spec.split('/')[0]
      if (!DUAL_BUILD_PACKAGES.has(top)) return
      return {path: require.resolve(spec, {paths: [projectRoot]})}
    })
  },
}

function generateEntrySource(modules, packages) {
  const lines = [
    "'use strict'",
    '// generated by scripts/test/bundle.mjs: lazy full-path export surface',
  ]
  for (const mod of modules) {
    // The entry is fed to esbuild via stdin with resolveDir = projectRoot,
    // so specs are repo-root relative (with './' so require does not treat
    // them as package specifiers).
    const relSpec = './' + path.relative(projectRoot, path.join(projectRoot, mod))
    lines.push(
      `Object.defineProperty(exports, ${JSON.stringify(mod)}, { enumerable: true, get: () => require(${JSON.stringify(relSpec)}) })`
    )
  }
  for (const spec of packages) {
    lines.push(
      `Object.defineProperty(exports, ${JSON.stringify('pkg:' + spec)}, { enumerable: true, get: () => require(${JSON.stringify(spec)}) })`
    )
  }
  return lines.join('\n') + '\n'
}

const VLQ_BASE64 = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
const VLQ_BASE64_MAP = new Map([...VLQ_BASE64].map((char, index) => [char, index]))

function decodeVLQAt(chars, i) {
  let result = 0
  let shift = 0
  while (i < chars.length) {
    const digit = VLQ_BASE64_MAP.get(chars[i])
    if (digit === undefined) break
    const continuation = digit & 32
    result += (digit & 31) << shift
    i++
    if (!continuation) break
    shift += 5
  }
  const negative = result & 1
  result >>>= 1
  return {value: negative ? -result : result, next: i}
}

/**
 * Walks the map's VLQ mappings and returns, per source index, the 1-based
 * line count that source needs (max referenced originalLine + 1). This is
 * the same decode node:test's SourceMap performs; we only track source
 * indices and original line numbers.
 */
function sourceLineCounts(map) {
  const counts = new Array(map.sources.length).fill(0)
  const chars = map.mappings
  let sourceIndex = 0
  let sourceLineNumber = 0
  let i = 0
  while (true) {
    if (chars[i] === ',') {
      i++
    } else {
      while (chars[i] === ';') {
        i++
      }
      if (i >= chars.length) break
    }
    const column = decodeVLQAt(chars, i)
    i = column.next
    // A segment without source/line/column/name fields ends at the next
    // separator (',' or ';') — the same rule node:test's SourceMap uses.
    if (i >= chars.length || chars[i] === ',' || chars[i] === ';') continue
    const sourceDelta = decodeVLQAt(chars, i)
    i = sourceDelta.next
    if (sourceDelta.value) sourceIndex += sourceDelta.value
    const lineDelta = decodeVLQAt(chars, i)
    sourceLineNumber += lineDelta.value
    i = lineDelta.next
    const columnDelta = decodeVLQAt(chars, i)
    i = columnDelta.next
    if (chars[i] !== ',' && chars[i] !== ';') {
      i = decodeVLQAt(chars, i).next
    }
    const needed = sourceLineNumber + 1
    if (sourceIndex < counts.length && needed > counts[sourceIndex]) {
      counts[sourceIndex] = needed
    }
  }
  return counts
}

/**
 * Rewrites bundle.js.map into the shape node:test's coverage mapper needs:
 *
 * - esbuild emits `sources` relative to the map file's directory, so any
 *   `sourceRoot` would double-prefix paths when Node resolves them against
 *   the sourceMappingURL. Sources are converted to absolute file URLs and
 *   sourceRoot is emptied.
 * - Node's coverage summary reads every mapped source from disk (or from
 *   sourcesContent). Bundled packages often ship no TS sources, the entry
 *   is a virtual stdin file, and UMD wrappers use `webpack://` URLs; those
 *   would make the summary throw ERR_SOURCE_MAP_MISSING_SOURCE. Each
 *   unreadable source keeps its own URL and gets a synthesized
 *   sourcesContent sized to the lines its mappings reference, so the mapper
 *   never touches a missing path and every mapped range stays in bounds
 *   (out-of-bounds ranges would leave functions with empty range lists,
 *   which crashes node:test's coverage merge across child processes).
 *   src/**\/*.ts mapping is unaffected and stays disk-backed.
 */
function fixCoverageSourceMap() {
  const mapPath = bundleFile + '.map'
  const map = JSON.parse(fs.readFileSync(mapPath, 'utf8'))
  const mapDir = path.dirname(bundleFile) + path.sep
  const lineCounts = sourceLineCounts(map)
  const sourcesContent = []
  map.sources = map.sources.map((source, index) => {
    let url
    try {
      url = new URL(source, pathToFileURL(mapDir)).href
    } catch {
      url = source
    }
    let readable = false
    try {
      readable = fs.existsSync(fileURLToPath(url))
    } catch {
      readable = false
    }
    if (readable) {
      sourcesContent.push(null)
      return url
    }
    // `'\n'.repeat(n)` splits into n lines under node:test's line splitter
    // (/(?<=\r?\n)/), so n lines of synthesized content need n newlines.
    const needed = lineCounts[index] ?? 1
    sourcesContent.push('\n'.repeat(needed))
    return url
  })
  map.sourceRoot = ''
  map.sourcesContent = sourcesContent
  fs.writeFileSync(mapPath, JSON.stringify(map))
}

/**
 * Content signature of every input that determines the bundle output: the
 * exported src module list, the bundled package list, esbuild's own version
 * and the config version. The bundle is only rebuilt when this changes, so
 * repeated test runs reuse the cached bundle.js (+ fixed map).
 */
function bundleSignature(modules, packages) {
  const hash = crypto.createHash('sha256')
  hash.update(`${BUNDLE_SIGNATURE_VERSION}\n`)
  hash.update(`${esbuildVersion}\n`)
  for (const mod of modules) {
    hash.update(`${mod}\0`)
    hash.update(fs.readFileSync(path.join(projectRoot, mod + '.ts')))
    hash.update('\0')
  }
  for (const pkg of packages) {
    hash.update(`pkg:${pkg}\0`)
  }
  return hash.digest('hex')
}

/**
 * Builds the editor-runtime bundle exactly ONCE and writes it to
 * `.cache/coc-test/bundle.js` (+ bundle.js.map): every src module is lazily
 * exported under its full repository path, so requiring it has no side
 * effects and all consumers share the same module instances. Third-party
 * packages are bundled in and exported under `pkg:<spec>` keys. The parent
 * calls this; test children just `require()` the file and never rebuild.
 */
export async function writeBundleFiles() {
  const modules = collectSrcModules()
  const packages = collectPackages()
  const hashFile = bundleFile + '.hash'
  const signature = bundleSignature(modules, packages)
  try {
    if (fs.readFileSync(hashFile, 'utf8') === signature &&
      fs.existsSync(bundleFile) && fs.existsSync(bundleFile + '.map')) {
      return {
        cached: true,
        moduleCount: modules.length,
        packageCount: packages.length,
        packages,
        durationMs: 0,
      }
    }
  } catch {
    // Missing or unreadable hash file: rebuild below.
  }
  const started = performance.now()
  fs.mkdirSync(path.dirname(bundleFile), {recursive: true})
  await build({
    stdin: {
      contents: generateEntrySource(modules, packages),
      resolveDir: projectRoot,
      sourcefile: 'bundle-entry.cjs',
    },
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node24',
    // Match the production build (esbuild.js): prefer each package's ESM
    // build. UMD wrappers use a parameterized require (e.g. jsonc-parser's
    // require2("./impl/format")) that esbuild cannot statically inline and
    // would resolve relative to the bundle file at runtime.
    mainFields: ['module', 'main'],
    plugins: [pinDualBuildPackages],
    outfile: bundleFile,
    // Linked external map: bundle.js stays small; fixCoverageSourceMap()
    // then rewrites the map so both --enable-source-maps stack traces and
    // node:test coverage resolve back to the real repo files.
    sourcemap: 'linked',
    sourcesContent: false,
    logLevel: 'silent',
  })
  fixCoverageSourceMap()
  fs.writeFileSync(hashFile, signature)
  return {
    cached: false,
    moduleCount: modules.length,
    packageCount: packages.length,
    packages,
    durationMs: Math.round(performance.now() - started),
  }
}
